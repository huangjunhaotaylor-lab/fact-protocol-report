/** 字典文案 → 属性安全转义 */
function escAttr(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/**
 * 生成一个解释图标的完整 HTML 字符串（供动态模板字符串内嵌）。
 * key 未命中字典时返回空串，不会产生坏图标。
 */
export function expIcon(key) {
  const text = EXPLORE_DICT[key];
  if (!text) return '';
  return `<span class="exp-ico" data-exp="${escAttr(text)}" role="note" aria-label="术语解释">?</span>`;
}

/**
 * 扫描 root 下所有带 data-exp-key 的元素并挂上解释：
 * - 若元素本身就是 .exp-ico 图标：从字典补 data-exp 文案；
 * - 否则在元素内部末尾追加一个图标（幂等，重复调用不会重复添加）。
 */
export function injectExplainers(root = document) {
  root.querySelectorAll('[data-exp-key]').forEach((elm) => {
    const text = EXPLORE_DICT[elm.dataset.expKey];
    if (!text) return;
    if (elm.classList.contains('exp-ico')) {
      if (!elm.getAttribute('data-exp')) elm.setAttribute('data-exp', text);
      return;
    }
    if (elm.dataset.expDone) return;
    elm.dataset.expDone = '1';
    const span = document.createElement('span');
    span.className = 'exp-ico';
    span.setAttribute('data-exp', text);
    span.setAttribute('role', 'note');
    span.setAttribute('aria-label', '术语解释');
    span.textContent = '?';
    elm.appendChild(span);
  });
}
